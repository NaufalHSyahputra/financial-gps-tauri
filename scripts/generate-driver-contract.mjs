import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../src/lib/drivers/', import.meta.url);
const binding = readFileSync(new URL('native/bindings.ts', root), 'utf8');
const typeSource = binding.split('/* Types */\n')[1].split('/* Tauri Specta runtime */')[0];
const operations = [];
const payloads = [];
for (const line of binding.split('/** Commands */')[1].split('/** Events */')[0].split('\n')) {
  if (!line.includes('__TAURI_INVOKE')) continue;
  const signature = /^\s+(\w+): \((.*)\) => typedError<(.*), AppError_Serialize>\(__TAURI_INVOKE\("(\w+)", (.*), options\)\),$/.exec(line);
  if (!signature) throw new Error(`Unsupported command declaration: ${line}`);
  const [, key, parameters, data, operation, payload] = signature;
  operations.push(`  ${key}(${parameters.replace(/(?:, )?options\?: InvokeOptions$/, '')}): Promise<DriverResult<${data}>>;`);
  const args = payload === 'undefined' ? [] : payload.slice(1, -1).split(',').map(arg => arg.trim());
  if (!args.every(arg => /^\w+$/.test(arg))) throw new Error(`Unsupported command payload: ${line}`);
  payloads.push(`  ${key}: ['${operation}'${args.map(arg => `, '${arg}'`).join('')}],`);
}
const start = '// Generated by scripts/generate-driver-contract.mjs from the native command schema.\n';
writeFileSync(new URL('contracts.ts', root), `${start}${typeSource}
export type DriverResult<T> = { status: 'ok'; data: T } | { status: 'error'; error: AppError };
export interface DatabaseDriver {
${operations.join('\n')}
}
export type Unsubscribe = () => void;
export interface DriverEvents {
  ledgerJobProgress(listener: (value: Progress_Serialize) => void): Promise<Unsubscribe>;
  ledgerIntegrityAlert(listener: (value: [Scope, AppError]) => void): Promise<Unsubscribe>;
  ledgerSyncStatus(listener: (value: [Scope, SyncStatus_Serialize]) => void): Promise<Unsubscribe>;
}
export interface SecretVaultDriver {
  testSavedTurso(scope: Scope): ReturnType<DatabaseDriver['ledgerSyncProbeSaved']>;
  validateTurso(input: TursoCredentials): ReturnType<DatabaseDriver['tursoCredentialsValidate']>;
  setStorageMode(scope: Scope, input: SetStorageMode): ReturnType<DatabaseDriver['ledgerStorageModeSet']>;
  setQuickUnlock(mutation: Mutation, input: KeychainChange_Deserialize): ReturnType<DatabaseDriver['ledgerKeychainSet']>;
}
export interface RuntimeDriver {
  commands: DatabaseDriver;
  events: DriverEvents;
  secrets: SecretVaultDriver;
}
`);
writeFileSync(new URL('operations.ts', root), `${start}import type { DatabaseDriver } from './contracts';\n\nexport const operations = {
${payloads.join('\n')}
} as const satisfies Record<keyof DatabaseDriver, readonly [string, ...string[]]>;\n`);
console.log(`Generated ${operations.length} transport-independent operation signatures.`);
